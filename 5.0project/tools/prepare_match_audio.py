"""Generate the A-only SPI wrapper from the unchanged shared879 core."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[1]
def expected():
 s=(ROOT/'common/photo_audio_link.v').read_text(encoding='utf-8');a=s.index('module photo_audio_spi_a #');s=s[a:s.index('\nendmodule',a)+len('\nendmodule')]
 s=s.replace('module photo_audio_spi_a #','module photo_match_audio_spi_a #',1)
 s=s.replace('photo_audio_fifo #','photo_match_audio_fifo #')
 s=s.replace('wire fifo_empty,fifo_full;', 'wire fifo_empty,fifo_full,fifo_ge511,fifo_ge512,fifo_lehalf;')
 s=s.replace('.full(fifo_full),.used(fifo_used));', '.full(fifo_full),.used(fifo_used),.ge511(fifo_ge511),.ge512(fifo_ge512),.lehalf(fifo_lehalf));')
 s=s.replace('fifo_used>=511','fifo_ge511').replace('fifo_used>=512','fifo_ge512')
 s=s.replace('fifo_used>(1<<(FIFO_AW-1))','!fifo_lehalf').replace('fifo_used<=(1<<(FIFO_AW-1))','fifo_lehalf')
 assert 'fifo_ge511' in s and '.ge511(fifo_ge511)' in s
 # Predecode transmit word selectors at the counter's upcoming edge.
 # This also works for HALF_DIV1, rather than relying on spare SPI clocks.
 marker='wire [31:0] received_word='
 pos=s.index(marker)
 predicted="""reg[4:0] tx_word_q;
wire tx_word_advance=state==TRANSFER && !change_audio && divider==HALF_DIV-1 && !spi_sclk && bit_index==31;
always @(posedge clk or posedge rst)
 if(rst)tx_word_q<=0;
 else if(state!=TRANSFER || change_audio)tx_word_q<=0;
 else begin
  tx_word_q[0]<=tx_word_advance ? word_index==0:word_index==1;
  tx_word_q[1]<=tx_word_advance ? word_index==1:word_index==2;
  tx_word_q[2]<=tx_word_advance ? word_index==2:word_index==3;
  tx_word_q[3]<=tx_word_advance ? word_index==3:word_index==4;
  tx_word_q[4]<=tx_word_advance ? word_index==4:word_index==5;
 end
"""
 s=s[:pos]+predicted+s[pos:]
 start=s.index('     if(REMOTE_HMI && hmi_transfer && word_index>=1')
 end=s.index('     if(finishing)',start)
 body=s[start:end]
 body=body.replace('word_index>=1 && word_index<=5','(|tx_word_q)')
 body=body.replace('case(word_index)','case(1\'b1)')
 for index in range(1,6):body=body.replace(str(index)+':begin','tx_word_q['+str(index-1)+']:begin')
 body=body.replace('word_index==1','tx_word_q[0]')
 s=s[:start]+body+s[end:]
 # Predict the idle counter's zero flag on the same transition as the counter.
 # This removes its wide comparator from SPI launch/receive clock enables.
 s=s.replace('reg [16:0] idle_wait;', 'reg [16:0] idle_wait;reg idle_ready;')
 s=s.replace('idle_wait==0','idle_ready')
 s=s.replace('idle_wait<=0;', 'idle_wait<=0;idle_ready<=1;')
 s=s.replace('idle_wait<=CLK_HZ/1000;', 'idle_wait<=CLK_HZ/1000;idle_ready<=CLK_HZ/1000==0;')
 s=s.replace("if(idle_wait!=0)idle_wait<=idle_wait-1'b1;", "if(!idle_ready)begin idle_wait<=idle_wait-1'b1;idle_ready<=idle_wait==1;end")
 condition='(payload_words==128 || (REMOTE_HMI && payload_words==132) || av_transfer || (relief_transfer && payload_words==385))'
 old='idle_wait<='+condition+' ? 0:CLK_HZ/1000;'
 assert s.count(old)==1
 s=s.replace(old,old+'idle_ready<='+condition+' || CLK_HZ/1000==0;')
 return '// Generated by tools/prepare_match_audio.py; all SPI framing and scheduling\n// remain879 code. Exact FIFO flags and SPI word selectors use registered predictions.\n'+s+'\n'
def verify():
 assert (ROOT/'common/match/photo_match_audio_spi.v').read_text(encoding='utf-8')==expected(),'A SPI wrapper is stale; run prepare_match_audio.py --write'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');a=p.parse_args()
 if a.write:(ROOT/'common/match/photo_match_audio_spi.v').write_text(expected(),encoding='utf-8')
 verify();print('PASS generated A SPI wrapper matches current shared source')
